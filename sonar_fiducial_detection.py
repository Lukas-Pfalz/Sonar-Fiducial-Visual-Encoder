"""## 4. Dataset and DataLoader

To plug in real data, replace `SyntheticSonarDataset` with a class that loads sonar frames and renders a heatmap from each frame's fiducial coordinates. The `__getitem__` contract is `(image_tensor[1,H,W], heatmap_tensor[1,H,W])`.
"""

class SyntheticSonarDataset(Dataset):
    def __init__(self, n_samples=512, H=256, W=256, seed_base=0):
        self.n = n_samples
        self.H, self.W = H, W
        self.seed_base = seed_base

    def __len__(self):
        return self.n

    def __getitem__(self, idx):
        img, hm, _ = generate_sonar_frame(self.H, self.W, seed=self.seed_base + idx)
        img = preprocess_sonar(img)
        return (
            torch.from_numpy(img).unsqueeze(0),
            torch.from_numpy(hm).unsqueeze(0),
        )


