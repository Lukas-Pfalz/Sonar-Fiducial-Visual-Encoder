"""## 2. Synthetic sonar generator

Real sonar imagery looks like grayscale photos with heavy multiplicative speckle. The generator below mimics that:

- Low-frequency background simulates seabed texture and sediment patches.
- Fiducials are bright Gaussian blobs at random positions (proxy for acoustic targets like corner reflectors or transponders).
- Speckle is gamma-distributed and multiplicative, which matches Rayleigh/K-distribution sonar statistics reasonably well.

Swap this whole section out for a real-data loader (image + per-fiducial pixel coordinates) when you have one. The rest of the pipeline doesn't care.
"""

def gaussian_blob(shape, center, sigma, amplitude=1.0):
    yy, xx = np.mgrid[0:shape[0], 0:shape[1]]
    return amplitude * np.exp(
        -((yy - center[0]) ** 2 + (xx - center[1]) ** 2) / (2 * sigma ** 2)
    )


def generate_sonar_frame(H=256, W=256, n_fid_range=(2, 6), seed=None):
    """Return (image, gt_heatmap, fiducial_coords) for one synthetic sonar frame."""
    rng = np.random.default_rng(seed)

    # background: low-amplitude noise + larger-scale sediment patches
    bg = rng.normal(0.30, 0.05, (H, W))
    bg = gaussian_filter(bg, sigma=3)
    patches = gaussian_filter(rng.normal(0, 1, (H, W)), sigma=25)
    bg = bg + 0.10 * patches

    # fiducials
    n_fid = int(rng.integers(*n_fid_range))
    fiducials: List[Tuple[int, int]] = []
    img = bg.copy()
    for _ in range(n_fid):
        cy = int(rng.integers(20, H - 20))
        cx = int(rng.integers(20, W - 20))
        sigma = float(rng.uniform(2.5, 4.0))
        amp = float(rng.uniform(0.7, 1.0))
        img = img + gaussian_blob((H, W), (cy, cx), sigma, amplitude=amp)
        fiducials.append((cy, cx))

    # multiplicative gamma speckle
    speckle = rng.gamma(shape=4.0, scale=0.25, size=(H, W))
    img = img * speckle

    img = np.clip(img, 0, None)
    img = img / (img.max() + 1e-8)

    # ground-truth heatmap: union of Gaussians centered on each fiducial
    hm = np.zeros((H, W), dtype=np.float32)
    for (cy, cx) in fiducials:
        hm = np.maximum(hm, gaussian_blob((H, W), (cy, cx), sigma=3.0))

    return img.astype(np.float32), hm, fiducials


