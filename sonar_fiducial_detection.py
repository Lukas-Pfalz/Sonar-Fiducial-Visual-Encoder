"""## 5. Model: small U-Net with heatmap head

U-Net works well here because fiducial detection is fundamentally a dense prediction problem: every output pixel says "is there a fiducial centered on me?" The skip connections preserve the fine localization signal the encoder otherwise loses to pooling.

The head is a `1x1 conv -> sigmoid` producing a `[0, 1]` heatmap. To extend:

- **Segmentation** of fiducial vs background: same head, different loss (BCE or Dice).
- **Multi-class fiducial detection** (e.g., separate IDs per marker): output `C` channels, one per class.
- **Sub-pixel localization** (CenterNet style): add a second head producing `(dy, dx)` offsets in `[-0.5, 0.5]`.
"""

class DoubleConv(nn.Module):
    def __init__(self, in_c, out_c):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(in_c, out_c, 3, padding=1),
            nn.BatchNorm2d(out_c),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_c, out_c, 3, padding=1),
            nn.BatchNorm2d(out_c),
            nn.ReLU(inplace=True),
        )
    def forward(self, x):
        return self.block(x)


class UNet(nn.Module):
    def __init__(self, in_c=1, out_c=1, base=32):
        super().__init__()
        self.d1  = DoubleConv(in_c, base)
        self.d2  = DoubleConv(base, base * 2)
        self.d3  = DoubleConv(base * 2, base * 4)
        self.bot = DoubleConv(base * 4, base * 8)
        self.u3  = DoubleConv(base * 8 + base * 4, base * 4)
        self.u2  = DoubleConv(base * 4 + base * 2, base * 2)
        self.u1  = DoubleConv(base * 2 + base,     base)
        self.pool = nn.MaxPool2d(2)
        self.up   = nn.Upsample(scale_factor=2, mode="bilinear", align_corners=False)
        self.head = nn.Conv2d(base, out_c, 1)

    def forward(self, x):
        c1 = self.d1(x)
        c2 = self.d2(self.pool(c1))
        c3 = self.d3(self.pool(c2))
        b  = self.bot(self.pool(c3))
        u3 = self.u3(torch.cat([self.up(b),  c3], dim=1))
        u2 = self.u2(torch.cat([self.up(u3), c2], dim=1))
        u1 = self.u1(torch.cat([self.up(u2), c1], dim=1))
        return torch.sigmoid(self.head(u1))


model = UNet().to(DEVICE)
n_params = sum(p.numel() for p in model.parameters())
print(f"params: {n_params / 1e6:.2f}M")

"""## 6. Loss and training loop

Plain MSE underweights the few positive pixels (fiducials are sparse). The weighted MSE below upweights positive regions by `1 + alpha * target`, the same idea as focal loss but adapted for heatmap regression. A drop-in alternative is the CenterNet penalty-reduced focal loss.

## 7. Peak detection and evaluation

Heatmap to fiducial coordinates: classic non-max-suppression via `maximum_filter`. A pixel is a peak if it equals the local max in a neighborhood and exceeds a confidence threshold.

For evaluation, match predicted peaks to ground-truth fiducials with a greedy nearest-neighbor assignment under a pixel-distance cap. From the matching we get TP / FP / FN and precision / recall.
"""

def focal_mse(pred, target, alpha=4.0):
    w = 1.0 + alpha * target
    return (w * (pred - target) ** 2).mean()


def train(model, train_dl, val_dl, n_epochs=5, lr=1e-3):
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=n_epochs)
    history = {"train": [], "val": []}

    try:
        for epoch in range(n_epochs):
            model.train()
            tl = 0.0
            for x, y in train_dl:
                x, y = x.to(DEVICE), y.to(DEVICE)
                pred = model(x)
                loss = focal_mse(pred, y)
                opt.zero_grad()
                loss.backward()
                opt.step()
                tl += loss.item() * x.size(0)
            tl /= len(train_dl.dataset)

            model.eval()
            vl = 0.0
            with torch.no_grad():
                for x, y in val_dl:
                    x, y = x.to(DEVICE), y.to(DEVICE)
                    vl += focal_mse(model(x), y).item() * x.size(0)
            vl /= len(val_dl.dataset)

            sched.step()
            history["train"].append(tl)
            history["val"].append(vl)
            print(f"epoch {epoch+1:02d}  train={tl:.4f}  val={vl:.4f}  lr={sched.get_last_lr()[0]:.2e}")
    except KeyboardInterrupt:
        print("\nTraining interrupted by user. Returning partial history.")
    return history


history = train(model, train_dl, val_dl, n_epochs=5, lr=1e-3)

