"""## 3. Sonar-specific preprocessing

Three operations that consistently help before feeding sonar into a CNN:

- **Log compression** narrows the dynamic range. Sonar returns span orders of magnitude.
- **Light despeckle** (Gaussian or median) removes high-frequency multiplicative noise without erasing the fiducials.
- **Per-image standardization** keeps the input well-conditioned for SGD regardless of gain settings.

If you have forward-looking sonar in polar coordinates (range x bearing), add a polar-to-Cartesian remap here. For side-scan or multibeam already in image space, this is enough.
"""

def preprocess_sonar(img: np.ndarray) -> np.ndarray:
    x = np.log1p(img * 10.0) / np.log1p(10.0)   # compress dynamic range
    x = gaussian_filter(x, sigma=0.8)           # despeckle
    x = (x - x.mean()) / (x.std() + 1e-8)       # standardize
    return x.astype(np.float32)


