def detect_peaks(hm: np.ndarray, threshold: float = 0.3, min_distance: int = 5):
    """Return ((y, x) coords, scores) of local maxima above `threshold`."""
    local_max = (maximum_filter(hm, size=min_distance) == hm) & (hm > threshold)
    coords = np.argwhere(local_max)
    scores = hm[local_max]
    order = np.argsort(-scores)
    return coords[order], scores[order]


def match_predictions(gt, pred, max_dist=5.0):
    """Greedy nearest matching between predicted and gt fiducials."""
    gt = np.asarray(gt, dtype=float).reshape(-1, 2)
    pred = np.asarray(pred, dtype=float).reshape(-1, 2)
    if len(gt) == 0:
        return 0, len(pred), 0
    if len(pred) == 0:
        return 0, 0, len(gt)

    used_gt = set()
    tp = 0
    for p in pred:
        dists = np.linalg.norm(gt - p, axis=1)
        for gi in np.argsort(dists):
            if gi in used_gt:
                continue
            if dists[gi] <= max_dist:
                used_gt.add(int(gi))
                tp += 1
            break
    fp = len(pred) - tp
    fn = len(gt) - tp
    return tp, fp, fn


def evaluate(model, n_frames=64, threshold=0.3, max_dist=5.0, seed_base=50_000):
    model.eval()
    TP = FP = FN = 0
    with torch.no_grad():
        for i in range(n_frames):
            img, _, fids = generate_sonar_frame(seed=seed_base + i)
            x = torch.from_numpy(preprocess_sonar(img)).unsqueeze(0).unsqueeze(0).to(DEVICE)
            pred_hm = model(x).squeeze().cpu().numpy()
            pred_pts, _ = detect_peaks(pred_hm, threshold=threshold)
            tp, fp, fn = match_predictions(fids, pred_pts, max_dist=max_dist)
            TP += tp; FP += fp; FN += fn
    precision = TP / max(TP + FP, 1)
    recall = TP / max(TP + FN, 1)
    f1 = 2 * precision * recall / max(precision + recall, 1e-8)
    print(f"frames={n_frames}  TP={TP}  FP={FP}  FN={FN}  "
          f"precision={precision:.3f}  recall={recall:.3f}  F1={f1:.3f}")
    return precision, recall, f1


_ = evaluate(model, n_frames=32, threshold=0.3, max_dist=5.0)

