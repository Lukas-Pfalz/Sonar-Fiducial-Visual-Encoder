"""## 9. Inference helper

Wrap the whole stack in a single function you can call on any new sonar frame (numpy array, single channel, any size that's divisible by 8).
"""

@dataclass
class Detection:
    y: float
    x: float
    score: float


def detect_fiducials(model, frame: np.ndarray, threshold: float = 0.3,
                     min_distance: int = 5) -> List[Detection]:
    """Run the detector end-to-end on a single sonar frame."""
    assert frame.ndim == 2, "expected single-channel sonar frame"
    H, W = frame.shape
    assert H % 8 == 0 and W % 8 == 0, "pad/crop so H, W are divisible by 8"

    proc = preprocess_sonar(frame)
    x = torch.from_numpy(proc).unsqueeze(0).unsqueeze(0).to(DEVICE)
    model.eval()
    with torch.no_grad():
        pred = model(x).squeeze().cpu().numpy()
    pts, scores = detect_peaks(pred, threshold=threshold, min_distance=min_distance)
    return [Detection(y=float(y), x=float(x), score=float(s))
            for (y, x), s in zip(pts, scores)]


